/* Screen (x,y) -> controller RAM: column x, row 127-y (as the stock UI leaves the scan mode;
 * verified in the emulator against stock screens). Filled rectangles only, so the
 * controller's scan direction never matters. */
void gfx_fill(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint16_t color)
{
    uint8_t c0, c1, r0, r1;
    if (!w || !h || x >= SCR_W || y >= SCR_H) return;
    if (x + w > SCR_W) w = SCR_W - x;
    if (y + h > SCR_H) h = SCR_H - y;
    c0 = x;  c1 = x + (w - 1);                   /* columns map 1:1 (visible 0..127) */
    r1 = 127 - y;  r0 = r1 - (h - 1);
    lcd_lock();
    lcd_cmd(0x15); lcd_data(c0); lcd_data(c1);   /* column window */
    lcd_cmd(0x75); lcd_data(r0); lcd_data(r1);   /* row window */
    lcd_cmd(0x5C);                               /* RAM write */
    lcd_data(color >> 8); lcd_data(color & 0xFF);
    lcd_fill_words(color, (uint16_t)w * h - 1);
    lcd_unlock();
}

