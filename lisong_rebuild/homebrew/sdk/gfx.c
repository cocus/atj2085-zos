void gfx_char(uint8_t x, uint8_t y, char c, uint8_t scale, uint16_t fg, uint16_t bg)
{
    uint8_t col, row, bits;
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c < 32 || c > 'Z') c = '?';
    gfx_fill(x, y, 6 * scale, 8 * scale, bg);
    for (col = 0; col < 5; col++) {
        bits = font5x7[c - 32][col];
        for (row = 0; row < 7; row++, bits >>= 1)
            if (bits & 1)
                gfx_fill(x + col * scale, y + row * scale, scale, scale, fg);
    }
}

void gfx_text(uint8_t x, uint8_t y, const char *s, uint8_t scale, uint16_t fg, uint16_t bg)
{
    while (*s) { gfx_char(x, y, *s++, scale, fg, bg); x += 6 * scale; }
}

void gfx_num(uint8_t x, uint8_t y, uint16_t n, uint8_t scale, uint16_t fg, uint16_t bg)
{
    char buf[6]; int8_t i = 5;
    buf[5] = 0;
    do { buf[--i] = '0' + n % 10; n /= 10; } while (n && i);
    gfx_text(x, y, buf + i, scale, fg, bg);
}
