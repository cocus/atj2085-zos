#!/usr/bin/env python3
"""Build the newbrec 16 KB boot record image (own code only, SDCC).

usage: python build.py [--target ximpro] [-o OUT.BIN] [--lcd-wait-div N] [--sdcc DIR]
Needs SDCC (sdcc, sdasz80, sdldz80): DIR, $SDCC_BIN, PATH or C:\\Program Files (x86)\\SDCC\\bin.
Steps: regs.h -> regs.inc, emblem -> logo.h (tools/brecpatch picture generator), compile, link
(head at 0x0000/0x0200/0x1B12 absolute, code from 0x1B15, variables from 0x0400), then the image: gaps
0x76, 0x55AA at 0x3FFC and the 16-bit word sum at 0x3FFE (the BROM's check). Prints the size budget.
Output: out/NEWBREC.BIN (+ map, symbols as JSON, size budget)."""
import os, re, sys, json, shutil, struct, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CODE_BASE, DATA_BASE, LIMIT = 0x1B15, 0x0400, 0x3FFC
FILL = 0x76


def find_tool(name, sdcc):
    cands = [os.path.join(sdcc, name)] if sdcc else []
    if os.environ.get('SDCC_BIN'):
        cands.append(os.path.join(os.environ['SDCC_BIN'], name))
    w = shutil.which(name)
    if w:
        cands.append(w)
    for d in (r'C:\Program Files (x86)\SDCC\bin', r'C:\Program Files\SDCC\bin'):
        cands.append(os.path.join(d, name))
    for c in cands:
        for x in (c, c + '.exe'):
            if os.path.isfile(x):
                return x
    sys.exit('%s not found (install SDCC or pass --sdcc DIR)' % name)


def run(cmd, cwd):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    out = r.stdout + r.stderr
    if r.returncode or 'rror' in out or 'Undefined' in out:
        sys.exit(' '.join(cmd) + '\n' + out)
    return out


def gen_regs_inc(src, dst):
    lines = [';; generated from regs.h - do not edit']
    for ln in open(src):
        m = re.match(r'^#define\s+([A-Z][A-Z0-9_]*)\s+(\(?[0-9A-Za-z_| ]+\)?)\s*(/\*.*)?$', ln)
        if m and not m.group(1).endswith('_H'):
            lines.append('%s = %s' % (m.group(1), m.group(2).strip()))
    open(dst, 'w').write('\n'.join(lines) + '\n')


def gen_logo(dst):
    sys.path.insert(0, os.path.join(ROOT, 'tools', 'brecpatch'))
    import brecpatch
    bg = (0, 0, 0)
    px = brecpatch.emblem(bg)
    rows, cols = [], []
    for y in range(brecpatch.H):
        m = 0
        col = 0
        for x in range(brecpatch.W):
            if px[y][x] != bg:
                m |= 1 << (23 - x)
                col = brecpatch.rgb565(*px[y][x])
        rows.append(m)
        cols.append(col)
    with open(dst, 'w') as f:
        f.write('/* generated by build.py from the tools/brecpatch emblem: 1 bit per pixel + one colour per row */\n')
        f.write('#define LOGO_W %d\n#define LOGO_H %d\n' % (brecpatch.W, brecpatch.H))
        f.write('static const uint8_t logo_mask[LOGO_H][3] = {\n')
        for m in rows:
            f.write('    {0x%02X, 0x%02X, 0x%02X},\n' % (m >> 16 & 255, m >> 8 & 255, m & 255))
        f.write('};\nstatic const uint16_t logo_col[LOGO_H] = {\n')
        for i in range(0, len(cols), 6):
            f.write('    ' + ', '.join('0x%04X' % c for c in cols[i:i + 6]) + ',\n')
        f.write('};\n')


def parse_ihx(txt):
    mem = {}
    for ln in txt.splitlines():
        if ln.startswith(':'):
            b = bytes.fromhex(ln[1:])
            if b[3] == 0:
                for i in range(b[0]):
                    mem[(b[1] << 8 | b[2]) + i] = b[4 + i]
    return mem


def rel_sizes(path):
    sz = {}
    for ln in open(path):
        m = re.match(r'^A (\S+) size ([0-9A-F]+) ', ln)
        if m:
            sz[m.group(1)] = sz.get(m.group(1), 0) + int(m.group(2), 16)
    return sz


def main():
    a = sys.argv[1:]
    opt = lambda n, d=None: a[a.index(n) + 1] if n in a else d
    target = opt('--target', 'ximpro')
    outbin = opt('-o')
    wdiv = opt('--lcd-wait-div', '1')
    sdcc_dir = opt('--sdcc')
    sdcc, sdas, sdld = (find_tool(n, sdcc_dir) for n in ('sdcc', 'sdasz80', 'sdldz80'))
    tdir = os.path.join(HERE, 'target', target)
    out = os.path.join(HERE, 'out')
    os.makedirs(out, exist_ok=True)
    gen_regs_inc(os.path.join(tdir, 'regs.h'), os.path.join(out, 'regs.inc'))
    gen_logo(os.path.join(out, 'logo.h'))
    inc = ['-I' + out, '-I' + tdir, '-I' + os.path.join(HERE, 'core')]
    ldr_src = os.path.join(tdir, 'stockldr.s')
    if os.path.exists(ldr_src):               # position-dependent blob for the ZRAM2 window (0x4000)
        run([sdas, '-g', '-l'] + inc + ['-o', os.path.join(out, 'stockldr.rel'), ldr_src], out)
        run([sdld, '-n', '-i', 'stockldr.ihx', os.path.join(out, 'stockldr.rel')], out)
        m = parse_ihx(open(os.path.join(out, 'stockldr.ihx')).read())
        lo, hi = min(m), max(m) + 1
        assert lo == 0x4000 and hi <= 0x47F0, 'stock loader must live in 0x4000-0x47EF'
        blob = bytes(m[x] for x in range(lo, hi))
        with open(os.path.join(out, 'stockldr.h'), 'w') as f:
            f.write('/* generated by build.py from the target stockldr.s: code for the ZRAM2 window (0x4000) */\n')
            f.write('#define STOCK_LDR_LEN %d\nstatic const uint8_t stock_ldr[STOCK_LDR_LEN] = {\n' % len(blob))
            for i in range(0, len(blob), 12):
                f.write('    ' + ', '.join('0x%02X' % c for c in blob[i:i + 12]) + ',\n')
            f.write('};\n')
    srcs = [os.path.join(tdir, 'head.s')]
    srcs += sorted(os.path.join(tdir, f) for f in os.listdir(tdir) if f.endswith(('.s', '.c')) and f not in ('head.s', 'stockldr.s'))
    srcs += sorted(os.path.join(HERE, 'core', f) for f in os.listdir(os.path.join(HERE, 'core')) if f.endswith('.c'))
    rels = []
    for s in srcs:
        rel = os.path.join(out, os.path.splitext(os.path.basename(s))[0] + '.rel')
        if s.endswith('.s'):
            run([sdas, '-g', '-l'] + inc + ['-o', rel, s], out)
        else:
            run([sdcc, '-mz80', '--reserve-regs-iy', '--opt-code-size', '--max-allocs-per-node', '20000',
                 '-DLCD_WAIT_DIV=' + wdiv] + inc + ['-c', s, '-o', rel], out)
        rels.append(rel)
    libdir = os.path.join(os.path.dirname(os.path.dirname(sdcc)), 'lib', 'z80')
    run([sdld, '-n', '-m', '-i', 'newbrec.ihx', '-b', '_CODE=0x%04X' % CODE_BASE, '-b', '_DATA=0x%04X' % DATA_BASE,
         '-k', libdir, '-l', 'z80'] + rels, out)
    mem = parse_ihx(open(os.path.join(out, 'newbrec.ihx')).read())
    if max(mem) >= LIMIT:
        sys.exit('code/data reaches %#06x, limit %#06x: DOES NOT FIT' % (max(mem), LIMIT))
    img = bytearray([FILL]) * 0x4000
    for ad, v in mem.items():
        img[ad] = v
    struct.pack_into('<H', img, 0x3FFC, 0x55AA)
    struct.pack_into('<H', img, 0x3FFE, sum(struct.unpack_from('<8191H', img)) & 0xFFFF)
    dst = outbin or os.path.join(out, 'NEWBREC.BIN')
    open(dst, 'wb').write(img)
    # symbols + budget
    syms = {}
    for ln in open(os.path.join(out, 'newbrec.map'), errors='replace'):
        for ad, n in re.findall(r'\b([0-9A-F]{8})\s+([A-Za-z_$.][\w$.]*)', ln):
            syms.setdefault(n, int(ad, 16))
    json.dump(syms, open(os.path.join(out, 'newbrec.sym'), 'w'), indent=1, sort_keys=True)
    budget, tot_code, tot_data = [], 0, 0
    for r in rels:
        s = rel_sizes(r)
        c = s.get('_CODE', 0)
        d = s.get('_DATA', 0)
        budget.append((os.path.basename(r)[:-4], c, d))
        tot_code += c
        tot_data += d
    code_hi = max(a for a in mem if a >= CODE_BASE)
    print('%-12s %6s %6s' % ('module', 'code', 'data'))
    for n, c, d in budget:
        print('%-12s %6d %6d' % (n, c, d))
    lib = code_hi + 1 - CODE_BASE - tot_code
    print('%-12s %6d' % ('(libs/pad)', lib))
    print('code %#06x-%#06x = %d B of %d (%#06x-%#06x), data %d B at %#06x, image %s' % (
        CODE_BASE, code_hi, code_hi + 1 - CODE_BASE, LIMIT - CODE_BASE, CODE_BASE, LIMIT, tot_data, DATA_BASE, dst))
    json.dump({'code': budget, 'code_end': code_hi + 1}, open(os.path.join(out, 'budget.json'), 'w'))


if __name__ == '__main__':
    main()
